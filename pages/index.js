import Head from "next/head";
import Link from "next/link";
import { safeSanityFetch, urlFor } from "../lib/sanity";

const recipesQuery = `*[_type == "recipe"]{
  _id,
  name,
  slug,
  mainImage,
}`;

export default function Home({ recipes }) {
  return (
    <div>
      <Head>
        <title>Anu's Kitchen 🍍</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <h1>Welcome to Anu's Kitchen 🍍</h1>

      <ul className="recipes-list">
        {recipes?.length > 0 &&
          recipes.map((recipe) => (
            <li key={recipe._id} className="recipe-card">
              <Link
                href={`/recipes/${recipe.slug.current}`}
                className="recipe-link"
              >
                <img
                  src={recipe.mainImage ? urlFor(recipe.mainImage)?.url() : "/favicon.ico"}
                  alt={recipe.name}
                />
                <span>{recipe.name}</span>
              </Link>
            </li>
          ))}
      </ul>
    </div>
  );
}

export async function getStaticProps() {
  const recipes = (await safeSanityFetch(recipesQuery)) || [];
  return { props: { recipes } };
}
